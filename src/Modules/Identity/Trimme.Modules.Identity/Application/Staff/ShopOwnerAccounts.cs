namespace Trimme.Modules.Identity.Application.Staff;

/// <summary>A shop's owner login as the admin's shop page shows it (D-158). <c>MustChangePassword</c>: a temporary password is waiting.</summary>
public sealed record ShopOwnerAccountResponse(
    Guid UserId, string DisplayName, string Email, bool IsDisabled, bool MustChangePassword, DateTimeOffset CreatedAt);

/// <summary>The new temporary password, returned once for the admin to hand to the owner (D-158); never stored in clear or logged.</summary>
public sealed record ShopOwnerPasswordResponse(ShopOwnerAccountResponse Account, string TemporaryPassword)
{
    public override string ToString() => $"{nameof(ShopOwnerPasswordResponse)} {{ UserId = {Account.UserId} }}";
}

internal sealed record ListShopOwnersQuery(Guid ShopId) : IQuery<Result<IReadOnlyList<ShopOwnerAccountResponse>>>;

internal sealed record ResetShopOwnerPasswordCommand(Guid ShopId, Guid UserId) : ICommand<Result<ShopOwnerPasswordResponse>>;

/// <summary>The shop's owners, for «المالك» on the admin's shop page (D-158, the client's request).</summary>
internal sealed class ListShopOwnersHandler(IShopDirectory shops, IAccountStore accounts)
    : IQueryHandler<ListShopOwnersQuery, Result<IReadOnlyList<ShopOwnerAccountResponse>>>
{
    public async Task<Result<IReadOnlyList<ShopOwnerAccountResponse>>> Handle(ListShopOwnersQuery query, CancellationToken cancellationToken)
    {
        if (await shops.FindAsync(new ShopId(query.ShopId), cancellationToken) is null)
        {
            return IdentityErrors.ShopNotFound();
        }

        var owners = await accounts.ListShopOwnersAsync(query.ShopId, cancellationToken);
        return owners.Select(ShopOwnerAccounts.ToResponse).ToList();
    }
}

/// <summary>
/// The admin gives a shop owner a new temporary password (D-158, the client's request: «أعيّن له كلمة مرور وأعطيه إياها»):
/// generated by the server as for barbers (D-146), shown once, replaced by the owner at the next sign-in (D-139). Every
/// session the owner still had ends, and a lockout is lifted. Only an owner of this shop qualifies: any other account,
/// a barber's login included, answers 404, so the permission can never reach an admin or a customer. Audited without
/// the password.
/// </summary>
internal sealed class ResetShopOwnerPasswordHandler(IAccountStore accounts, SessionManager sessions, IAuditLog audit)
    : ICommandHandler<ResetShopOwnerPasswordCommand, Result<ShopOwnerPasswordResponse>>
{
    public async Task<Result<ShopOwnerPasswordResponse>> Handle(ResetShopOwnerPasswordCommand command, CancellationToken cancellationToken)
    {
        var owners = await accounts.ListShopOwnersAsync(command.ShopId, cancellationToken);
        if (owners.SingleOrDefault(o => o.UserId == command.UserId) is not { } owner)
        {
            return IdentityErrors.UserNotFound();
        }

        if (owner.IsDisabled)
        {
            return ShopOwnerAccounts.Disabled();
        }

        var password = TemporaryPasswords.New();
        var set = await accounts.SetTemporaryPasswordAsync(owner.UserId, password, cancellationToken);
        if (set.IsFailure)
        {
            return set.Error;
        }

        // The revocation saves the audit entry with it.
        audit.Record(new AuditRecord(
            "shop_user.password_reset", "User", owner.UserId.ToString(), new ShopId(command.ShopId), "Temporary password generated by an admin"));
        await sessions.RevokeAllAsync(owner.UserId, keep: null, SessionRevocationReason.PasswordReset, cancellationToken);
        return new ShopOwnerPasswordResponse(ShopOwnerAccounts.ToResponse(owner with { MustChangePassword = true }), password);
    }
}

internal static class ShopOwnerAccounts
{
    public static ShopOwnerAccountResponse ToResponse(ShopOwnerAccountRow row) =>
        new(row.UserId, row.DisplayName ?? string.Empty, row.Email ?? string.Empty, row.IsDisabled, row.MustChangePassword, row.CreatedAt);

    public static Error Disabled() =>
        Error.Conflict("shop_user.disabled", "The account is disabled; turn it on before giving it a password.");
}
