import type { Metadata } from 'next';
import Image from 'next/image';
import { getTranslations } from 'next-intl/server';
import { ProfessionalStatusBadge } from '@/components/admin/ProfessionalStatusBadge';
import { ShopFrame } from '@/components/shop/ShopFrame';
import { Badge } from '@/components/ui/Badge';
import { ButtonLink } from '@/components/ui/Button';
import { EmptyState, ErrorState, PermissionDenied } from '@/components/ui/states';
import { asLocale } from '@/i18n/routing';
import { getServerApi } from '@/lib/api/server';
import { localizedName } from '@/lib/i18n/localized';

export const metadata: Metadata = { robots: { index: false, follow: false } };

/**
 * «الحلاقون» (D-145, D-146): the owner's barbers. The owner adds a barber (who gets a login at once, with a temporary
 * password generated by the server) and edits each one on their page: profile, photo, WhatsApp number (also the
 * sign-in), the services they do, their login, and whether they take bookings. A barber's shop never changes (D-011).
 */
export default async function ShopBarbersPage({ params }: PageProps<'/[locale]/shop/barbers'>) {
  const { locale: raw } = await params;
  const locale = asLocale(raw);
  const t = await getTranslations({ locale, namespace: 'shopBarbers' });
  const tLogin = await getTranslations({ locale, namespace: 'barberLogins' });

  return (
    <ShopFrame locale={locale} path="/shop/barbers" title={t('title')}>
      {async (me, shop) => {
        if (shop.status === 'Suspended') return <EmptyState icon="shield" title={t('title')} />;
        if (!me.permissions.includes('Shop.Barbers.Manage')) return <PermissionDenied homeHref="/shop" />;
        const api = await getServerApi();
        const { data: professionals } = await api.GET('/api/v1/shop/professionals');
        if (!professionals) return <ErrorState />;
        // A handful of barbers per shop: one read each, side by side, for the login badge.
        const logins = await Promise.all(
          professionals.map((p) =>
            api
              .GET('/api/v1/shop/professionals/{professionalId}/login', {
                params: { path: { professionalId: p.id } },
              })
              .then((r) => r.data),
          ),
        );

        return (
          <div className="flex max-w-[960px] flex-col gap-5">
            <div className="flex flex-wrap items-center justify-between gap-3">
              <p className="max-w-[640px] text-body text-text-secondary">{t('intro')}</p>
              <ButtonLink href="/shop/barbers/new" size="md" icon="plus">
                {t('add')}
              </ButtonLink>
            </div>
            {professionals.length === 0 ? (
              <EmptyState icon="users" title={t('empty')} body={t('emptyBody')} />
            ) : (
              <ul className="grid gap-3 md:grid-cols-2" data-testid="shop-barbers">
                {professionals.map((p, index) => {
                  const login = logins[index];
                  const name = localizedName(locale, p.nameAr, p.nameEn);
                  const specialty = localizedName(locale, p.specialtyAr ?? '', p.specialtyEn);
                  const loginState = !login?.enabled
                    ? { tone: 'neutral' as const, label: tLogin('state.off') }
                    : login.mustChangePassword
                      ? { tone: 'warning' as const, label: tLogin('state.temporary') }
                      : { tone: 'success' as const, label: tLogin('state.on') };
                  return (
                    <li
                      key={p.id}
                      className="flex items-start gap-4 rounded-card border border-border bg-surface p-5 shadow-e1"
                      data-testid={`shop-barber-${p.id}`}
                    >
                      {p.avatarUrl ? (
                        <Image
                          src={p.avatarUrl}
                          alt=""
                          width={56}
                          height={56}
                          unoptimized
                          className="size-14 shrink-0 rounded-full border border-border object-cover"
                        />
                      ) : (
                        <span
                          aria-hidden="true"
                          className="flex size-14 shrink-0 items-center justify-center rounded-full bg-bg-muted text-h3 font-bold text-navy-900"
                        >
                          {name.slice(0, 1)}
                        </span>
                      )}
                      <div className="flex min-w-0 flex-1 flex-col gap-2">
                        <h2 className="truncate text-h3 font-bold text-navy-900">{name}</h2>
                        {specialty && <p className="text-caption text-text-secondary">{specialty}</p>}
                        <div className="flex flex-wrap gap-2">
                          <ProfessionalStatusBadge status={p.status} />
                          <Badge tone={loginState.tone}>{loginState.label}</Badge>
                        </div>
                        <ButtonLink
                          href={`/shop/barbers/${p.id}`}
                          size="sm"
                          variant="outline"
                          icon="edit"
                          className="self-start"
                          aria-label={t('manageAria', { name })}
                        >
                          {t('manage')}
                        </ButtonLink>
                      </div>
                    </li>
                  );
                })}
              </ul>
            )}
          </div>
        );
      }}
    </ShopFrame>
  );
}
